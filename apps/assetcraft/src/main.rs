//! AssetCraft desktop app: a Bridge-style, read-only navigator window.
//!
//! `assetcraft [FOLDER]` opens FOLDER (else the last folder, else Pictures, else home).
//! Prefs live in the per-user config folder (see `assetcraft_ui_egui::prefs_file::config_path`)
//! and are saved when favorites, view settings or the panel layout change, and on exit.
//! Thumbnails are cached on disk in the suite cache (`docs/design/cache.md`; the folder from
//! `assetcraft_cache::root`: `%LOCALAPPDATA%\AssetCraft\Cache`, `~/Library/Caches/AssetCraft`,
//! `~/.cache/assetcraft`, or `ASSETCRAFT_CACHE_DIR`), up to 1 GiB. Thumbnails from before C1 are
//! deleted once, in the background (`assetcraft_thumbs::disk::retire_legacy`).
//! The open folder is watched (`assetcraft-watch`); where watching fails, F5 still refreshes.
//! The window, Dock, taskbar and Alt-Tab icon comes from `assets/app-icon/` (the elephant); on
//! Windows `build.rs` also embeds `assetcraft.ico` in the exe for Explorer and the Start menu.

#![cfg_attr(all(windows, not(debug_assertions)), windows_subsystem = "windows")]

use assetcraft_engine::{Session, SystemLauncher};
use assetcraft_fs::RealFs;
use assetcraft_thumbs::{DEFAULT_DISK_BUDGET, DiskCache};
use assetcraft_ui_egui::{Navigator, PrefsStore, prefs_file};
use std::path::PathBuf;
use std::process::ExitCode;
use std::sync::Arc;

/// Reverse-DNS app id: Linux hicolor icon name and Wayland app id (`assets/app-icon/hicolor/`).
const APP_ID: &str = "ai.storyteller.assetcraft";

/// The window, Dock, taskbar and app-switcher icon (`assets/app-icon/`, regenerated by
/// `packaging/icons.py`). macOS gets the tile inside Apple's transparent margin so it matches the
/// size of other Dock icons; Windows and Linux get the full-bleed tile. Same split as FilmCraft
/// (`filmcraft/apps/filmcraft/src/main.rs`, `app_icon`).
#[cfg(target_os = "macos")]
const ICON_PNG: &[u8] = include_bytes!("../../../assets/app-icon/assetcraft-macos-512.png");
#[cfg(not(target_os = "macos"))]
const ICON_PNG: &[u8] = include_bytes!("../../../assets/app-icon/hicolor/256x256/apps/ai.storyteller.assetcraft.png");

/// The decoded icon, or none (the OS default) if the bytes don't decode: never a reason not to start.
fn app_icon() -> egui::IconData {
    eframe::icon_data::from_png_bytes(ICON_PNG).unwrap_or_default()
}

struct App {
    navigator: Navigator,
    store: PrefsStore,
}

impl eframe::App for App {
    fn ui(&mut self, ui: &mut egui::Ui, _frame: &mut eframe::Frame) {
        self.navigator.ui(ui);
        if !self.store.maybe_save(&self.navigator.session().prefs())
            && let Some(error) = self.store.last_error().map(str::to_owned)
            && self.navigator.message().is_none()
        {
            self.navigator.notify(error);
        }
    }

    fn on_exit(&mut self) {
        if !self.store.save_now(&self.navigator.session().prefs())
            && let Some(error) = self.store.last_error()
        {
            eprintln!("assetcraft: {error}");
        }
    }
}

fn main() -> ExitCode {
    let path = prefs_file::config_path();
    let prefs = path.as_deref().map(prefs_file::load).unwrap_or_default();
    let store = PrefsStore::new(path, prefs.clone());
    let mut session = Session::new(Arc::new(RealFs::new()), Arc::new(SystemLauncher), prefs);
    let cache_root = assetcraft_cache::root::resolve_here(&assetcraft_cache::root::ASSETCRAFT, None);
    if let Some(root) = cache_root.dir {
        session = session.with_thumb_cache(DiskCache::open(root, DEFAULT_DISK_BUDGET));
    }
    if let Some(old) = prefs_file::legacy_thumb_dir() {
        let _ = std::thread::Builder::new()
            .name("assetcraft-retire-thumbs".into())
            .spawn(move || assetcraft_thumbs::disk::retire_legacy(&old));
    }
    // Watch your Cut plays the track on the default output device (opened on the first ▶).
    session.set_player(Arc::new(assetcraft_playback::DevicePlayer::new()));
    let mut navigator = Navigator::new(session);
    if let Some(folder) = std::env::args_os().nth(1).map(PathBuf::from) {
        navigator.open_folder(&folder);
    }

    let options = eframe::NativeOptions {
        viewport: egui::ViewportBuilder::default()
            .with_title("AssetCraft")
            .with_app_id(APP_ID)
            .with_icon(app_icon())
            .with_inner_size([1360.0, 860.0])
            .with_min_inner_size([720.0, 420.0]),
        ..eframe::NativeOptions::default()
    };
    let mut app = App { navigator, store };
    let create = move |cc: &eframe::CreationContext<'_>| -> Result<Box<dyn eframe::App>, _> {
        // Folder events arrive on the watcher's thread; wake the UI so they show without input.
        let ctx = cc.egui_ctx.clone();
        let waker: assetcraft_watch::Waker = Arc::new(move || ctx.request_repaint());
        app.navigator.set_watcher(Box::new(assetcraft_watch::NotifyWatcher::new(Some(waker))));
        Ok(Box::new(app))
    };
    match eframe::run_native("AssetCraft", options, Box::new(create)) {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("assetcraft: could not open a window: {error}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_app_icon_decodes_to_a_square_rgba_image() {
        let icon = app_icon();
        let side: u32 = if cfg!(target_os = "macos") { 512 } else { 256 };
        assert_eq!((icon.width, icon.height), (side, side));
        assert_eq!(icon.rgba.len(), (side * side * 4) as usize);
        // The elephant, not the empty default: some pixels are opaque.
        assert!(icon.rgba.iter().skip(3).step_by(4).any(|&alpha| alpha == 255));
    }

    #[test]
    fn the_app_id_names_the_hicolor_icons() {
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../assets/app-icon/hicolor");
        for size in [16, 24, 32, 48, 64, 128, 256, 512] {
            let png = dir.join(format!("{size}x{size}/apps/{APP_ID}.png"));
            assert!(png.is_file(), "{} missing", png.display());
        }
        assert!(dir.join(format!("scalable/apps/{APP_ID}.svg")).is_file());
    }
}
